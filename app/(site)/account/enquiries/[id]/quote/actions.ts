"use server";

import { revalidatePath } from "next/cache";
import { redirect } from "next/navigation";
import { currentUser, sessionClient } from "@/lib/supabase-server";

/**
 * Sending a quotation.
 *
 * Three writes in a deliberate order, because of how the database
 * protects a quotation once it has left draft:
 *
 *   1. insert the quotation as 'draft'
 *   2. insert its lines
 *   3. update totals and set it to 'sent'
 *
 * guard_quotation_immutability freezes the commercial content the
 * moment status is anything other than draft, so the lines have to go in
 * first. A different price after that is a new version, never an edit,
 * which is the right rule for a document somebody may rely on.
 *
 * The reference (QUO-26-00001) is generated by a trigger, not here.
 */

interface Line {
  description: string;
  quantity: number;
  unit_code: string;
  unit_price_minor: number;
}

function money(value: FormDataEntryValue | null, minorUnits: number): number {
  const n = Number(String(value ?? "").replace(/,/g, "").trim());
  if (!Number.isFinite(n) || n < 0) return 0;
  return Math.round(n * 10 ** minorUnits);
}

export async function sendQuotation(enquiryId: string, formData: FormData) {
  const user = await currentUser();
  if (!user) redirect("/sign-in");

  const supabase = await sessionClient();

  // Read the enquiry through RLS. A supplier who is not party to it sees
  // nothing here, so this doubles as the permission check.
  const { data: enquiry } = await supabase
    .from("enquiries")
    .select("id, buyer_company_id, supplier_company_id, status")
    .eq("id", enquiryId)
    .maybeSingle();

  if (!enquiry) return { ok: false, message: "That enquiry is not available." };
  if (enquiry.status === "closed") {
    return { ok: false, message: "That enquiry has been closed." };
  }

  const currency = String(formData.get("currency") ?? "GBP").slice(0, 3);
  const { data: cur } = await supabase
    .from("currencies")
    .select("minor_units")
    .eq("code", currency)
    .maybeSingle();
  const minorUnits = cur?.minor_units ?? 2;

  // Lines arrive as parallel arrays from the repeating rows in the form.
  const descriptions = formData.getAll("line_description").map(String);
  const quantities = formData.getAll("line_quantity").map(String);
  const units = formData.getAll("line_unit").map(String);
  const prices = formData.getAll("line_price").map(String);

  const lines: Line[] = [];
  for (let i = 0; i < descriptions.length; i++) {
    const description = descriptions[i]?.trim();
    const quantity = Number(quantities[i]);
    const unit_code = units[i];
    if (!description || !Number.isFinite(quantity) || quantity <= 0 || !unit_code) {
      continue;
    }
    lines.push({
      description,
      quantity,
      unit_code,
      unit_price_minor: money(prices[i], minorUnits),
    });
  }

  if (lines.length === 0) {
    return { ok: false, message: "Add at least one priced line." };
  }

  const subtotal = lines.reduce(
    (sum, l) => sum + Math.round(l.quantity * l.unit_price_minor),
    0
  );
  const shipping = money(formData.get("shipping"), minorUnits);
  const other = money(formData.get("other_charges"), minorUnits);

  const text = (name: string) => {
    const v = String(formData.get(name) ?? "").trim();
    return v === "" ? null : v;
  };
  const leadTime = Number(formData.get("lead_time_days"));

  const { data: created, error: insertError } = await supabase
    .from("quotations")
    .insert({
      enquiry_id: enquiry.id,
      supplier_company_id: enquiry.supplier_company_id,
      buyer_company_id: enquiry.buyer_company_id,
      status: "draft",
      currency,
      incoterm: text("incoterm"),
      lead_time_days: Number.isFinite(leadTime) && leadTime > 0 ? leadTime : null,
      payment_terms: text("payment_terms"),
      packaging_notes: text("packaging_notes"),
      notes: text("notes"),
      valid_until: text("valid_until"),
      created_by: user.id,
    })
    .select("id")
    .single();

  if (insertError || !created) {
    return {
      ok: false,
      message: insertError?.message ?? "The quotation could not be created.",
    };
  }

  const { error: linesError } = await supabase.from("quotation_lines").insert(
    lines.map((l, i) => ({
      quotation_id: created.id,
      description: l.description,
      quantity: l.quantity,
      unit_code: l.unit_code,
      unit_price_minor: l.unit_price_minor,
      sort_order: i,
    }))
  );

  if (linesError) {
    // The quotation is still a draft, so it is invisible to the buyer.
    // Leaving it rather than deleting it keeps the reference allocated
    // and gives us something to look at if this keeps happening.
    return { ok: false, message: linesError.message };
  }

  const { error: sendError } = await supabase
    .from("quotations")
    .update({
      subtotal_minor: subtotal,
      shipping_minor: shipping,
      other_charges_minor: other,
      total_minor: subtotal + shipping + other,
      status: "sent",
      sent_at: new Date().toISOString(),
    })
    .eq("id", created.id);

  if (sendError) return { ok: false, message: sendError.message };

  revalidatePath("/account/enquiries");
  revalidatePath("/account/quotations");
  redirect(`/account/quotations/${created.id}?sent=1`);
}
